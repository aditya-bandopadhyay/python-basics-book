# Playing with Numbers -- Code 2.4: Trying out arithmetic operators
# (book source: ch02_numbers.tex, line 367)

x = 7
y = 3
print(x + y)   # 10
print(x - y)   # 4
print(x * y)   # 21
print(x / y)   # 2.3333... (always a float)
print(x // y)  # 2  (floor division: whole number)
print(x % y)   # 1  (remainder)
print(x ** y)  # 343 (7 raised to power 3)
